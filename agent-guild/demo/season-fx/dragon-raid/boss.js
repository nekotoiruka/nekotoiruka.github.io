// 火山の岩場（溶岩の川）: 赤黒い空と噴煙、奥を溶岩の川が横切る。黒い岩の床にひびが赤く光る。手前に岩の柱、火の粉が舞う。
function makeStage(host) {
    const { rect, bands, speck, ridge, rockFloor, leftTint, flick } = host.stagekit;
    return {
        id: 'dragon-lava', dark: 0.0,
        paint(g, W, H, rng) {
            bands(g, -40, W + 40, 0, 62, ['#1a0d17', '#241018', '#33141a', '#47191b', '#5e2219']);
            ridge(g, rng, -40, W + 40, 62, 16, '#1b1016', 5);
            // 遠くの火山（噴火）
            g.fillStyle = '#140b11';
            g.beginPath();
            g.moveTo(250, 64);
            g.lineTo(300, 18);
            g.lineTo(316, 18);
            g.lineTo(372, 64);
            g.fill();
            rect(g, 300, 17, 16, 2, '#ff7a2a');
            for (let i = 0; i < 14; i++)
                rect(g, 302 + rng.range(0, 12), 19 + i * 3, 2, 3, i % 2 ? '#c8401a' : '#ff8a2a');
            for (let i = 0; i < 30; i++)
                rect(g, 296 + rng.range(-20, 26) + i * 0.6, 14 - rng.range(0, 14), rng.range(4, 9), 3, rng.pick(['#3a2228', '#2c1a20', '#4a2a2a']));
            // 溶岩の川（奥を横切る。冒険者の立つ所にはかからない）
            rect(g, -40, 62, W + 80, 18, '#160c10');
            for (let x = -40; x < W + 40; x += 2) {
                const y = 68 + Math.round(Math.sin(x / 23) * 2 + Math.sin(x / 7) * 0.6);
                rect(g, x, y, 2, 7, '#c8401a');
                rect(g, x, y + 1, 2, 4, '#ff7a2a');
                if ((x / 2) % 5 === 0)
                    rect(g, x, y + 2, 2, 1, '#ffd25a');
            }
            rect(g, -40, 76, W + 80, 4, '#1a1014');
            // 黒い岩の床
            rockFloor(g, rng, -40, W + 40, 80, H, '#181116', ['#3a2f36', '#342a31', '#40343a', '#2f262d'], '#120c10', '#4e4048');
            for (let i = 0; i < 18; i++) { // 赤く光るひび
                let x = rng.range(100, W + 30), y = rng.range(90, H - 6);
                for (let k = 0; k < 7; k++) {
                    rect(g, x, y, 2, 1, k % 3 ? '#a8361a' : '#ff7a2a');
                    x += rng.range(-3, 4);
                    y += rng.range(0, 3);
                }
            }
            // ボスのうしろの溶岩だまり
            g.fillStyle = '#1a0f12';
            g.beginPath();
            g.ellipse(52, 132, 60, 12, 0, 0, Math.PI * 2);
            g.fill();
            g.fillStyle = '#c8401a';
            g.beginPath();
            g.ellipse(52, 131, 54, 9, 0, 0, Math.PI * 2);
            g.fill();
            g.fillStyle = '#ff7a2a';
            g.beginPath();
            g.ellipse(50, 130, 44, 6, 0, 0, Math.PI * 2);
            g.fill();
            speck(g, rng, 10, 125, 96, 135, 30, ['#ffd25a', '#ffb040'], 2);
            speck(g, rng, -40, 84, W + 40, H, 200, ['#4a3c44', '#221a20'], 1);
            leftTint(g, H, '160,40,10', 0.3);
        },
        lights: (f) => [
            { x: 52, y: 128, r: 80 + flick(f, 1, 5), a: 0.8, col: '#ff7a2a' },
            { x: 120, y: 70, r: 60 + flick(f, 2, 4), a: 0.7, col: '#ff6a2a' }, { x: 230, y: 70, r: 60 + flick(f, 3, 4), a: 0.7, col: '#ff6a2a' }, { x: 340, y: 70, r: 60 + flick(f, 4, 4), a: 0.7, col: '#ff6a2a' },
            { x: 308, y: 20, r: 40, a: 0.6, col: '#ff9a3a' },
        ],
        front(g, { px, keep, H, W }) {
            if (keep <= 0)
                return;
            g.globalAlpha = keep;
            for (const [x0, wdt, side] of [[-18, 26, 1], [W - 8, 28, -1]]) {
                const x = Math.round(x0 + px);
                for (let y = -20; y < H + 20; y += 3) { // ふちがでこぼこの岩
                    const e = Math.round(3 * Math.sin(y / 11 + x0) + 2 * Math.sin(y / 4.3));
                    rect(g, side > 0 ? x : x - e, y, wdt + e, 3, '#100a0e');
                    rect(g, side > 0 ? x + wdt + e - 2 : x - e, y, 2, 3, '#3a1812');
                }
            }
            g.globalAlpha = 1;
        },
        motes: { kind: 'ember', n: 30, col: '#ff9a3a' },
    };
}
// ================= 大魔法（#104。BossModule の chainFinale。受け口と共通の部品は本体の chainkit.ts＝kit.chainkit） =================
// 大瀑布: 空の魔法陣が裂けて、天の水を巻く大渦になる。渦の底が抜けて大瀑布が竜を打ち、水の波が床を画面の端まで走る。溶岩に水がかかって、画面いっぱいに蒸気が爆ぜ、雨が降る。
function makeChainFinale(host) {
    const { aft, bloom, chargeK, column, darkCurve, doneFlash, fallers, floorGlow, gather, heavyFeel, hitFlash, light, smoke, streaks, wideRings } = host.chainkit;
    const { R, TAU, ease, lerp, sparkBurst, win } = host.ultkit;
    const { mistBlob } = host.fxkit;
    const { Rng } = host.rng;
    // ---- 1. 大瀑布: 空の魔法陣が裂けて、水を巻く大渦になる → 渦の底が抜けて、大瀑布が竜を打つ → 溶岩に水がかかって、画面いっぱいの蒸気の爆発 ----
    function vortex(ctx, x, y, r, alpha, frame, spin) {
        if (alpha <= 0 || r <= 1)
            return;
        ctx.save();
        ctx.translate(x, y);
        ctx.scale(1, 0.3);
        ctx.globalAlpha = 0.8 * alpha;
        ctx.fillStyle = '#081a34';
        ctx.beginPath();
        ctx.arc(0, 0, r * 0.45, 0, TAU);
        ctx.fill();
        ctx.globalAlpha = 0.55 * alpha;
        ctx.fillStyle = '#123a6a';
        ctx.beginPath();
        ctx.arc(0, 0, r, 0, TAU);
        ctx.fill();
        ctx.globalCompositeOperation = 'lighter';
        for (let j = 0; j < 7; j++)
            for (let rr = 8; rr < r; rr += 2.2) {
                const an = (j / 7) * TAU + rr * 0.06 - frame * spin;
                ctx.globalAlpha = alpha * (0.35 + 0.65 * (1 - rr / r));
                ctx.fillStyle = rr % 9 < 3 ? '#ffffff' : '#6ab8ff';
                ctx.fillRect(R(Math.cos(an) * rr) - 2, R(Math.sin(an) * rr) - 2, 4, 4);
            }
        ctx.restore();
    }
    function dFallsBack(a, c, sky) {
        const p = a.phase, k = chargeK(c, p);
        if (k > 0 && p < c.impact)
            light(a, sky.x, sky.y + 20, 120 + 100 * k, 0.8 * k, '#6ab8ff');
        const hit = aft(c, p, -0.006, 0.3);
        if (hit > 0 && hit < 1) {
            light(a, a.body.x, a.body.y, 280, 1.0 * (1 - hit), '#bfe8ff');
            floorGlow(a.ctx, a.body.x, a.foot.y + 6, 60 + 320 * ease(hit), '#6ab8ff', 0.8 * (1 - hit));
        }
    }
    function dFalls(a, c, sky) {
        const { ctx, phase: p } = a;
        const k = chargeK(c, p), bx = a.body.x + 4, fy = a.foot.y + 6, by = a.body.y;
        gather(a, c, sky, 210, '#6ab8ff');
        const vlive = k * (1 - aft(c, p, 0.12, 0.26));
        vortex(ctx, sky.x, sky.y, 60 + 90 * ease(k), vlive, a.frame, 0.05 + 0.15 * k);
        // 渦のふちからこぼれる滝のしずく
        if (k > 0 && p < c.impact)
            fallers(ctx, sky.x, sky.y + 10, fy, 120 * k, p * 40, `${a.seed}:drip`, ['#bfe8ff', '#6ab8ff'], k * 0.8, 40, 0, 6, true);
        // 大瀑布（着弾の少し前から、しばらく落ち続ける）
        const fall = win(p, c.impact - 0.008, c.impact - 0.001), live = 1 - aft(c, p, 0.08, 0.16);
        if (fall > 0 && live > 0) {
            const e = ease(fall);
            column(ctx, sky.x, sky.y + 4, lerp(sky.x, bx, e), lerp(sky.y, fy, e), 34, 70, ['#123a6add', '#2a6ab8ee', '#6ab8ff', '#cfeeff'], live, a.frame, '#e8f8ff', 1);
        }
        // 着弾: しぶきの冠、水の波が床を画面の端まで走り、溶岩に触れたところから蒸気が噴く
        const hit = aft(c, p, 0, 0.3);
        if (hit > 0 && hit < 1) {
            bloom(a, bx, by, hit, '#8fd3ff', 0.5);
            streaks(a, bx, by, hit, '#bfe8ff', `${a.seed}:fallst`, 36);
            sparkBurst(ctx, bx, fy - 10, hit, `${a.seed}:crown`, ['#ffffff', '#bfe8ff', '#4a9ae0'], 120, 220, 260, 3);
            for (const dir of [-1, 1]) {
                const x = bx + dir * (20 + 330 * ease(hit));
                ctx.save();
                ctx.globalAlpha = 0.85 * (1 - hit);
                for (let i = 0; i < 28; i++) {
                    const yy = fy - 8 + i * 2.5, xx = x - dir * (i % 4) * 3;
                    ctx.fillStyle = i < 5 ? '#ffffff' : i < 14 ? '#8fd3ff' : '#2a6ab8';
                    ctx.fillRect(R(xx), R(yy - 12 * Math.sin((i / 28) * Math.PI)), dir * -26, 3);
                }
                ctx.restore();
            }
            wideRings(ctx, bx, fy, hit, '#8fd3ff');
            // 蒸気の大爆発（白いかたまりが画面の半分まで盛り上がる）
            const rng = new Rng(`${a.seed}:steam`);
            for (let i = 0; i < 26; i++) {
                const sx = bx + rng.range(-180, 180) * ease(hit), sy = fy - rng.range(0, 120) * ease(hit), r = rng.range(16, 34) * (0.5 + hit);
                mistBlob(ctx, sx, sy, r, r * 0.6, i % 3 ? '#e8eef6' : '#a8b4c4', 0.75 * (1 - hit * hit));
            }
        }
        const af = aft(c, p, 0.08, 0.36);
        if (af > 0 && af < 1) {
            smoke(a, bx, fy, af, `${a.seed}:steam2`, '#c8d0dc', 24, 300);
            fallers(ctx, a.W / 2, -10, fy + 20, a.W, af * 2, `${a.seed}:rain`, ['#bfe8ff', '#8fd3ff'], (1 - af) * 0.9, 90, -10, 6, true);
        }
        hitFlash(a, c, '#cfeeff', 0.35);
        doneFlash(a, c);
    }
    const fallsAfter = (c) => [0.02, 0.04, 0.06].map((d) => ({ t: c.impact + d, k: 0.5 }));
    return { id: 'd-falls', top: dFalls, back: dFallsBack, dark: darkCurve(0.4), feel: heavyFeel({ big: 1.3, sink: 6, after: fallsAfter }) };
}
