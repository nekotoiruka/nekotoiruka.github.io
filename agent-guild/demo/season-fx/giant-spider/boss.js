// ================= 大魔法（#104。BossModule の chainFinale。受け口と共通の部品は本体の chainkit.ts＝kit.chainkit） =================
// 月光の大鎌: 空の魔法陣に霜の光の三日月が生まれ、回りながら大きくなる。振り下ろされて画面を斜めに断ち切り、断ち口が画面の端から端まで光ってそこから爆ぜる。森じゅうの糸が切れて舞い落ちる。
function makeChainFinale(host) {
    const { aft, bloom, chargeK, darkCurve, doneFlash, fallers, gather, heavyFeel, hitFlash, light, ringBurst, streaks, wideRings } = host.chainkit;
    const { TAU, clamp01, ease, glowLine, lerp, slashArc, sparkBurst, win } = host.ultkit;
    const { Rng } = host.rng;
    const scytheSwing = (c, p) => win(p, c.impact - 0.008, c.impact);
    function crescentShape(ctx, x, y, r, rot, alpha) {
        if (alpha <= 0 || r <= 1)
            return;
        ctx.save();
        ctx.translate(x, y);
        ctx.rotate(rot);
        ctx.globalCompositeOperation = 'lighter';
        for (const [k, col, al] of [[1.25, '#6ab8ff', 0.35], [1, '#bfe8ff', 0.9], [0.8, '#ffffff', 1]]) {
            ctx.globalAlpha = alpha * al;
            ctx.fillStyle = col;
            ctx.beginPath();
            ctx.arc(0, 0, r * k, -2.2, 2.2);
            ctx.arc(r * 0.35, 0, r * k * 0.85, 2.0, -2.0, true);
            ctx.closePath();
            ctx.fill();
        }
        ctx.restore();
    }
    function spMoonBack(a, c, sky) {
        const p = a.phase, k = chargeK(c, p);
        if (k > 0 && p < c.impact)
            light(a, sky.x, sky.y + 20, 120 + 120 * k, 0.9 * k, '#bfe8ff');
        const hit = aft(c, p, 0, 0.32);
        if (hit > 0 && hit < 1)
            light(a, a.body.x, a.body.y, 320, 1.0 * (1 - hit), '#dff6ff');
    }
    const cutLine = (a) => { const bx = a.body.x + 4, by = a.body.y, an = 0.62; return { x0: bx - Math.cos(an) * 300, y0: by - Math.sin(an) * 300, x1: bx + Math.cos(an) * 300, y1: by + Math.sin(an) * 300 }; };
    function spMoon(a, c, sky) {
        const { ctx, phase: p } = a;
        const k = chargeK(c, p), bx = a.body.x + 4, by = a.body.y, fy = a.foot.y + 6;
        gather(a, c, sky, 200, '#bfe8ff');
        // 三日月: 陣の中心で生まれ、回りながら大きくなる
        const sw = scytheSwing(c, p);
        if (k > 0 && sw < 1) {
            const r = 12 + 26 * ease(k), cy = sky.y + 48;
            glowLine(ctx, sky.x, sky.y, sky.x, cy, 4 * k, '#9fe8ff', k); // 陣から三日月へ、光が降りてつながる
            crescentShape(ctx, sky.x, cy, r, a.frame / 6, k);
            if (k > 0.3)
                fallers(ctx, sky.x, cy - 40, cy + 60, r * 2, p * 30, `${a.seed}:frost`, ['#e8f8ff', '#9fe8ff'], k, 30, 0, 2, true);
        }
        // 振り下ろし: 大きな弧（画面をまたぐ）
        if (sw > 0 && p < c.impact + 0.02) {
            const fade = 1 - aft(c, p, 0, 0.02);
            slashArc(ctx, bx + 220, by - 180, 300, Math.PI * 0.62, lerp(Math.PI * 0.62, Math.PI * 1.02, ease(sw)), 40 * fade, ['#9fe8ff', '#ffffff'], fade);
        }
        // 断ち口: 画面の端から端まで光り、しばらく残って、そって爆ぜる
        const L = cutLine(a), cut = aft(c, p, 0, 0.004), cg = 1 - aft(c, p, 0.12, 0.24);
        if (cut > 0 && cg > 0) {
            glowLine(ctx, L.x0, L.y0, L.x1, L.y1, 10 * cg + 2, '#9fe8ff', cg);
            glowLine(ctx, L.x0, L.y0, L.x1, L.y1, 3, '#ffffff', cg);
        }
        const hit = aft(c, p, 0, 0.3);
        if (hit > 0 && hit < 1) {
            bloom(a, bx, by, hit, '#bfe8ff', 0.55);
            streaks(a, bx, by, hit, '#dff6ff', `${a.seed}:moonst`, 36);
            ringBurst(a, bx, by, hit, '#bfe8ff', '#ffffff', 2);
            for (let i = 0; i < 9; i++) {
                const t = i / 8, x = lerp(L.x0, L.x1, 0.2 + t * 0.6), y = lerp(L.y0, L.y1, 0.2 + t * 0.6);
                sparkBurst(ctx, x, y, clamp01(hit * 1.3 - i * 0.03), `${a.seed}:cutb${i}`, ['#ffffff', '#bfe8ff'], 18, 50, 40);
            }
            wideRings(ctx, bx, fy, hit, '#bfe8ff');
        }
        // 余韻: 断たれた糸が森じゅうから舞い落ち、霜のきらめき
        const af = aft(c, p, 0.04, 0.36);
        if (af > 0 && af < 1) {
            const rng = new Rng(`${a.seed}:threads`);
            ctx.save();
            ctx.globalCompositeOperation = 'lighter';
            for (let i = 0; i < 60; i++) {
                const x = rng.range(-10, a.W) + Math.sin(af * 5 + i) * 8, y = lerp(-10, fy + 10, (af * 1.4 + rng.next()) % 1), Ll = rng.range(8, 18), an = rng.range(0, TAU) + af * 3;
                ctx.globalAlpha = (1 - af) * 0.8;
                ctx.strokeStyle = '#dff6ff';
                ctx.lineWidth = 1;
                ctx.beginPath();
                ctx.moveTo(x, y);
                ctx.lineTo(x + Math.cos(an) * Ll, y + Math.sin(an) * Ll);
                ctx.stroke();
            }
            ctx.restore();
            fallers(ctx, a.W / 2, -10, fy, a.W, af, `${a.seed}:glit`, ['#ffffff', '#9fe8ff'], 1 - af, 60, 0, 1, true);
        }
        hitFlash(a, c, '#dff6ff', 0.45);
        doneFlash(a, c);
    }
    const moonAfter = (c) => [0.03, 0.06].map((d) => ({ t: c.impact + d, k: 0.5 }));
    return { id: 'sp-moon', top: spMoon, back: spMoonBack, dark: darkCurve(0.45), feel: heavyFeel({ big: 1.3, after: moonAfter }) };
}
