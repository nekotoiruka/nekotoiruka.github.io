// ================= 大魔法（#104。BossModule の chainFinale。受け口と共通の部品は本体の chainkit.ts＝kit.chainkit） =================
// 岩の大雨: 空の魔法陣の下に、苔むした大岩が三十あまり浮かび出て、群れの上一面に影が落ちる。大岩が真下へ、回りながら次々に落ちて群れを叩きつぶし（ゴブリンが跳ね飛ぶ）、最後に頭目へいちばん大きな岩。岩は地面に残る。
function makeChainFinale(host) {
    const { aft, bloom, chargeK, darkCurve, doneFlash, gather, heavyFeel, hitFlash, leafBurst, light, ringBurst, shoutEnd, smoke, streaks, wideRings } = host.chainkit;
    const { R, TAU, crater, dustCloud, ease, glowDisc, lerp, rocks, sparkBurst, speedLines, win } = host.ultkit;
    const { goblinSil, rock } = host.fxkit;
    const { Rng } = host.rng;
    const BOULDER_N = 36;
    const BOULDER_T0 = 0.028, BOULDER_T1 = 0.006; // 着弾のどれだけ前から前まで、岩が落ちつづけるか
    function boulderAt(a, c, i) {
        const rng = new Rng(`boulder:${i}`);
        const last = i === BOULDER_N - 1;
        // 落ちる所: 頭目のまわりから、群れのいる地面いっぱいに（手前の討伐隊にはかからない）
        const x = last ? a.body.x + 4 : a.body.x + 4 + rng.range(-80, 96), y = a.foot.y + 8 + (last ? 0 : rng.range(-10, 30));
        const t = last ? c.impact - 0.003 : lerp(c.impact - BOULDER_T0, c.impact - BOULDER_T1, i / (BOULDER_N - 2)) + rng.range(-0.0012, 0.0012);
        // 浮かぶ所: 落ちる所の真上（陣の下の空）。落ちるときは、ほぼまっすぐ下へ
        const hx = x + rng.range(-6, 6), hy = last ? 24 : rng.range(6, 44);
        return { x, y, t, r: last ? 30 : rng.range(8, 16), hx, hy, rot: rng.range(0, TAU), spin: rng.range(-3, 3) };
    }
    const boulderHits = (c) => Array.from({ length: BOULDER_N - 1 }, (_, i) => ({ t: lerp(c.impact - BOULDER_T0, c.impact - BOULDER_T1, i / (BOULDER_N - 2)) + 0.004, k: i % 3 === 0 ? 0.45 : 0.25 }));
    function gBoulderBack(a, c) {
        const p = a.phase, k = chargeK(c, p), ctx = a.ctx;
        for (let i = 0; i < BOULDER_N; i++) {
            const b = boulderAt(a, c, i), land = p >= b.t + 0.004;
            if (!land && k > 0) {
                const s = win(p, b.t - 0.02, b.t + 0.004);
                ctx.save();
                ctx.globalAlpha = (0.2 + 0.5 * s) * k;
                ctx.fillStyle = '#1a1408';
                ctx.beginPath();
                ctx.ellipse(b.x, b.y, b.r * (2.4 - 1.2 * s), b.r * 0.4, 0, 0, TAU);
                ctx.fill();
                ctx.restore();
            }
            if (land) {
                const d = win(p, b.t + 0.004, b.t + 0.03);
                if (d < 1)
                    light(a, b.x, b.y - 10, 60, 0.6 * (1 - d), '#ffd890');
                crater(ctx, b.x, b.y + 2, b.r * 1.4, 1 - aft(c, p, 0.24, 0.36), '#c8a060');
            }
        }
        const hit = aft(c, p, 0, 0.3);
        if (hit > 0 && hit < 1)
            light(a, a.body.x, a.body.y, 280, 1.1 * (1 - hit), '#ffe2a0');
    }
    function gBoulder(a, c, sky) {
        const { ctx, phase: p } = a;
        const bx = a.body.x + 4, fy = a.foot.y + 8, by = a.body.y;
        gather(a, c, sky, 70, '#d8c890');
        for (let i = 0; i < BOULDER_N; i++) {
            const b = boulderAt(a, c, i);
            const appear = ease(win(p, shoutEnd(c) + (i % 12) * 0.0012, shoutEnd(c) + (i % 12) * 0.0012 + 0.01));
            const fall = win(p, b.t - 0.006, b.t + 0.004) ** 2, gone = aft(c, p, 0.22, 0.34);
            if (appear <= 0 || gone >= 1)
                continue;
            // 重さのある落ち方: 浮かんでいるあいだは小さくゆれ、落ちはじめは遅く、だんだん速く（2乗）。回りながら、着地の瞬間に止まる
            const bob = (1 - Math.min(1, fall * 4)) * Math.sin(a.frame / 15 + i) * 2;
            const x = lerp(b.hx, b.x, fall), y = lerp(b.hy + bob, b.y - b.r * 0.6, fall);
            if (fall > 0 && fall < 1)
                speedLines(ctx, x, b.r * 2, y - 70, y, a.frame, fall, '#f4ecd0', 8);
            if (p < b.t + 0.004)
                glowDisc(ctx, x, y, b.r * 1.8, '#c8e080', 0.35 * appear * (1 - fall));
            ctx.save();
            ctx.globalAlpha = (1 - gone);
            rock(ctx, x, y, b.r * appear, b.rot + fall * b.spin, i, '#6a6050', '#9a9080', '#3a3428');
            if (i % 2 === 0) {
                ctx.fillStyle = '#5a8a3a';
                ctx.fillRect(R(x - b.r * 0.5), R(y - b.r * 0.6), R(b.r * 0.6), 2);
            } // 苔
            ctx.restore();
            const d = win(p, b.t + 0.004, b.t + 0.035);
            if (d > 0 && d < 1) {
                dustCloud(a, b.x, b.y, d, `gb${i}`, b.r / 10);
                rocks(a, b.x, b.y, d, `gbr${i}`, 8, 50 + b.r * 3);
                if (i % 2 === 0)
                    sparkBurst(ctx, b.x, b.y - 4, d, `gbs${i}`, ['#ffe2a0', '#ffffff'], 8, 36);
                for (let j = 0; j < (i % 3 === 0 ? 2 : 1); j++) {
                    ctx.save();
                    ctx.globalAlpha = 1 - d;
                    ctx.translate(b.x + (j ? 1 : -1) * 30 * d, b.y - 40 * Math.sin(d * Math.PI));
                    ctx.rotate(d * 8 * (j ? 1 : -1));
                    goblinSil(ctx, 0, 0, 0.9, i);
                    ctx.restore();
                }
            }
        }
        const hit = aft(c, p, 0, 0.3);
        if (hit > 0 && hit < 1) {
            bloom(a, bx, by, hit, '#e8d890', 0.45);
            streaks(a, bx, by, hit, '#fff2c0', `${a.seed}:bst`, 40);
            ringBurst(a, bx, fy - 8, hit, '#ffd166', '#c8a060', 2);
            wideRings(ctx, bx, fy, hit, '#e8dcb0');
            rocks(a, bx, fy, hit, `${a.seed}:bigrock`, 60, 260);
            dustCloud(a, bx - 50, fy, hit, `${a.seed}:bd1`, 3);
            dustCloud(a, bx + 50, fy, hit, `${a.seed}:bd2`, 3);
            leafBurst(ctx, bx, by - 30, hit, `${a.seed}:bleaf`, 50);
        }
        const af = aft(c, p, 0.08, 0.36);
        if (af > 0 && af < 1)
            smoke(a, bx + 40, fy, af, `${a.seed}:bhaze`, '#b8a888', 24, 300);
        hitFlash(a, c, '#fff2d0', 0.3);
        doneFlash(a, c);
    }
    return { id: 'g-boulder', top: gBoulder, back: gBoulderBack, dark: darkCurve(0.3, 0), feel: heavyFeel({ big: 1.4, push: 5, sink: 8, hits: boulderHits }) };
}
