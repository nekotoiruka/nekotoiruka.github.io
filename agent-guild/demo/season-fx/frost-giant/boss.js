// ================= 舞台（#119。BossModule の stage。受け口と共通の部品は本体の stagekit.ts＝kit.stagekit） =================
// 吹雪の雪原: 灰青の空、雪の峰と針葉樹。雪の床に足あと。ボスの足もとに雪の吹きだまり（足を少し埋める）。雪が斜めに降る。手前に雪をかぶった木。
function makeStage(host) {
    const { rect, bands, ridge, softFloor, leftTint, tree, pine } = host.stagekit;
    function drift(g, foot, cols) {
        const x0 = foot.x - 50, x1 = foot.x + 52;
        for (let x = x0; x < x1; x++) {
            const t = (x - x0) / (x1 - x0);
            const h = Math.round(5 + 4 * Math.sin(t * Math.PI) + 1.5 * Math.sin(x * 0.35));
            const y = foot.y + 5 - h;
            rect(g, x, y, 1, h + 2, cols[1]);
            rect(g, x, y, 1, 2, cols[0]);
            if ((x * 7) % 11 === 0)
                rect(g, x, y, 1, 1, cols[3]);
            rect(g, x, foot.y + 4, 1, 2, cols[2]);
        }
    }
    return {
        id: 'giant-snow', dark: -0.06,
        paint(g, W, H, rng) {
            bands(g, -40, W + 40, 0, 64, ['#6a7a94', '#7a8aa2', '#8c9cb2', '#a0aec2']);
            ridge(g, rng, -40, W + 40, 50, 22, '#8a9ab4', 7, '#e8f0f8');
            ridge(g, rng, -40, W + 40, 62, 10, '#a8b8cc', 5, '#f0f6fc');
            for (let i = 0; i < 30; i++) {
                const x = rng.range(-40, W + 40);
                tree(g, x, 72, rng.range(16, 28), rng.pick(['#3a5060', '#34495a']), '#e8f0f8');
            }
            rect(g, -40, 72, W + 80, 8, '#d0dce8');
            softFloor(g, rng, -40, W + 40, 80, H, ['#dce6f0', '#e4ecf4', '#d0dcea', '#c8d6e6'], 0.2);
            for (let i = 0; i < 40; i++) {
                const x = rng.range(-40, W + 40), y = rng.range(86, H);
                rect(g, x, y, rng.range(6, 18), 1, '#b8c8dc');
            }
            for (let i = 0; i < 14; i++) {
                const x = 200 + i * 9, y = 120 + ((i * 7) % 30);
                rect(g, x, y, 3, 2, '#b0c2d8');
            } // 足あと
            leftTint(g, H, '90,140,200', 0.25);
        },
        lights: () => [{ x: 220, y: 40, r: 180, a: 0.55, col: '#e6f2ff' }, { x: 220, y: 160, r: 170, a: 0.55 }, { x: 70, y: 100, r: 90, a: 0.4, col: '#9fd8ff' }],
        bossFront: (g, { foot }) => drift(g, foot, ['#f2f8fc', '#dce8f2', '#c4d4e6', '#ffffff']),
        front(g, { px, keep, H, W }) {
            if (keep <= 0)
                return;
            g.globalAlpha = keep;
            const x = Math.round(px);
            pine(g, 2 + x, H + 4, 150, 22, '#18242e', '#c8d8e8');
            pine(g, W - 2 + x, H + 4, 170, 24, '#18242e', '#c8d8e8');
            g.globalAlpha = 1;
        },
        motes: { kind: 'snow', n: 70, col: '#ffffff' },
    };
}
// ================= 大魔法（#104。BossModule の chainFinale。受け口と共通の部品は本体の chainkit.ts＝kit.chainkit） =================
// 溶岩の大瀑布: 空の魔法陣が赤熱し、陣に溶けた溶岩がたまって滴る。陣の底が抜けて溶岩の大瀑布が巨人を打ち、氷のよろいが砕け、雪原が一面の湯気の爆発になる。足もとに溶岩が広がって、ゆっくり冷えていく。
function makeChainFinale(host) {
    const { aft, bloom, chargeK, column, crackPts, darkCurve, doneFlash, fallers, flames, gather, glowPath, heavyFeel, hitFlash, light, mix, smoke, streaks, wideRings } = host.chainkit;
    const { TAU, ease, lerp, sparkBurst, win } = host.ultkit;
    const { flameBall, mistBlob, shard } = host.fxkit;
    const { Rng } = host.rng;
    // ---- 1. 溶岩の大瀑布: 空の魔法陣が赤熱し、陣に溶けた溶岩がたまって滴る → 陣の底が抜けて、溶岩の大瀑布が巨人を打つ → 雪原が一面の湯気の爆発、溶岩が雪を溶かして広がる ----
    function fLavaBack(a, c, sky) {
        const p = a.phase, k = chargeK(c, p), ctx = a.ctx, fy = a.foot.y + 6;
        if (k > 0 && p < c.impact + 0.1)
            light(a, sky.x, sky.y + 20, 140 + 120 * k, 1.1 * k, '#ff7a2a');
        const pool = aft(c, p, -0.002, 0.08), cool = aft(c, p, 0.2, 0.4);
        if (pool > 0) {
            const w = 30 + 150 * ease(pool);
            ctx.save();
            ctx.globalAlpha = 0.9;
            ctx.fillStyle = mix('#ff6a1a', '#3a1a10', cool);
            ctx.beginPath();
            ctx.ellipse(a.body.x, fy, w, 10 + 14 * ease(pool), 0, 0, TAU);
            ctx.fill();
            ctx.fillStyle = mix('#ffd166', '#5a2a18', cool);
            ctx.beginPath();
            ctx.ellipse(a.body.x - 6, fy - 2, w * 0.6, 6 + 8 * ease(pool), 0, 0, TAU);
            ctx.fill();
            ctx.restore();
            for (let j = 0; j < 10; j++)
                glowPath(ctx, crackPts(`${a.seed}:lc${j}`, a.body.x, fy, (j / 10) * TAU, w, 6, 0.3), 1, 1.2, '#ffb040', 1 - cool * 0.5);
            light(a, a.body.x, fy - 10, 200 + w, 1.2 * (1 - cool * 0.6), '#ff8a3a');
        }
    }
    function fLava(a, c, sky) {
        const { ctx, phase: p } = a;
        const k = chargeK(c, p), bx = a.body.x + 4, fy = a.foot.y + 6, by = a.body.y;
        // 吹雪を沈めて、熱の色を際立たせる
        const dk = k * (1 - aft(c, p, 0, 0.12));
        if (dk > 0) {
            ctx.save();
            ctx.globalAlpha = 0.55 * dk;
            ctx.fillStyle = '#100810';
            ctx.fillRect(-a.W, -a.H, a.W * 3, a.H * 3);
            ctx.restore();
        }
        gather(a, c, sky, 15, '#ff7a2a', 1.1);
        // 陣にたまる熾火（赤熱した円盤・したたる滴）
        if (k > 0 && p < c.impact + 0.02) {
            ctx.save();
            ctx.translate(sky.x, sky.y);
            ctx.scale(1, 0.32);
            ctx.globalAlpha = k;
            ctx.fillStyle = '#5a0e08';
            ctx.beginPath();
            ctx.arc(0, 0, 30 + 50 * k, 0, TAU);
            ctx.fill();
            ctx.fillStyle = '#ff5a1a';
            ctx.beginPath();
            ctx.arc(0, 0, 24 + 42 * k, 0, TAU);
            ctx.fill();
            ctx.fillStyle = '#ffd166';
            ctx.beginPath();
            ctx.arc(-6, -4, 12 + 22 * k, 0, TAU);
            ctx.fill();
            ctx.restore();
            const rng = new Rng(`${a.seed}:drop`);
            for (let i = 0; i < 12; i++) {
                const u = (rng.next() + p * rng.range(30, 50)) % 1, x = sky.x + rng.range(-50, 50) * k;
                flameBall(ctx, x, lerp(sky.y + 6, fy, u * u), 3, k * (1 - u));
            }
        }
        const fall = win(p, c.impact - 0.008, c.impact - 0.001), live = 1 - aft(c, p, 0.07, 0.14);
        if (fall > 0 && live > 0) {
            const e = ease(fall);
            column(ctx, sky.x, sky.y + 4, lerp(sky.x, bx, e), lerp(sky.y, fy, e), 26, 54, ['#5a0e08', '#c0281a', '#ff6a2a', '#ffd166'], live, a.frame, '#fff2b0', 1);
            flames(ctx, lerp(sky.x, bx, e), lerp(sky.y, fy, e), 60, 60, a.frame / 16, `${a.seed}:lvf`, live, 50, 4);
        }
        const hit = aft(c, p, 0, 0.3);
        if (hit > 0 && hit < 1) {
            bloom(a, bx, by, hit, '#ff8a3a', 0.6);
            streaks(a, bx, by, hit, '#ffd166', `${a.seed}:lvst`, 40);
            sparkBurst(ctx, bx, fy - 10, hit, `${a.seed}:lvsplash`, ['#ffd166', '#ff6a2a', '#c0281a'], 90, 200, 260, 3);
            wideRings(ctx, bx, fy, hit, '#ffb040');
            // 湯気の大爆発（雪原の半分を覆う）
            const rng = new Rng(`${a.seed}:fsteam`);
            for (let i = 0; i < 30; i++) {
                const sx = bx + rng.range(-220, 220) * ease(hit), sy = fy - rng.range(0, 140) * ease(hit), r = rng.range(16, 36) * (0.5 + hit);
                mistBlob(ctx, sx, sy + 3, r, r * 0.6, '#6a6878', 0.6 * (1 - hit * hit));
                mistBlob(ctx, sx, sy, r * 0.9, r * 0.5, '#f0f0f8', 0.8 * (1 - hit * hit));
            }
            const rng2 = new Rng(`${a.seed}:fice`);
            for (let i = 0; i < 40; i++) {
                const an = rng2.range(0, TAU), sp = rng2.range(40, 220) * ease(hit);
                ctx.save();
                ctx.globalAlpha = 1 - hit * hit;
                shard(ctx, bx + Math.cos(an) * sp, by + Math.sin(an) * sp * 0.7 + 120 * hit * hit, rng2.range(6, 14), rng2.range(3, 6), an + hit * 6, '#9fd0f0', '#ffffff', '#3a6a9a');
                ctx.restore();
            }
        }
        const af = aft(c, p, 0.08, 0.38);
        if (af > 0 && af < 1) {
            smoke(a, bx, fy, af, `${a.seed}:fsteam2`, '#9a9aa8', 26, 320);
            fallers(ctx, bx, by - 80, fy, 200, af * 1.4, `${a.seed}:fember`, ['#ff8a3a', '#ffd166'], 1 - af, 50, 0, 1, true);
        }
        hitFlash(a, c, '#ff9a4a', 0.35);
        doneFlash(a, c);
    }
    const lavaAfter = (c) => [0.02, 0.045, 0.07].map((d) => ({ t: c.impact + d, k: 0.5 }));
    // ---- 2. 胸に灯る火種: 陣から火種のひと粒が落ちて巨人の胸に沈み、胸の奥で脈打ちながら燃え広がる（体のひびが内から橙に光る）→ 凍った体を内側から砕く → 砕けたところから雪原に一本の温かい光の道がのび、雪が溶けていく ----
    return { id: 'f-lava', top: fLava, back: fLavaBack, dark: darkCurve(0.3, 0.1), feel: heavyFeel({ big: 1.35, after: lavaAfter }) };
}
